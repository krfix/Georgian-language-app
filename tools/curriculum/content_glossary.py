def _n(*parts):
    return ("\n".join(p[0] for p in parts), "\n".join(p[1] for p in parts))


def F(base, en, pl, *notes):
    ne, np_ = _n(*notes) if notes else ("", "")
    return (base, en, pl, ne, np_)


def FN(base, en, pl, note_en, note_pl, *notes):
    ne, np_ = _n(*notes) if notes else ("", "")
    return (base, en, pl, (note_en + " " + ne).strip(), (note_pl + " " + np_).strip())


